    const languageSelect = document.getElementById("language-select");
    const menuToggle = document.getElementById("menu-toggle");
    const nav = document.getElementById("site-nav");
    const themeToggle = document.getElementById("theme-toggle");
    const themeIcon = document.getElementById("theme-icon");

    function setTheme(theme) {
      const next = theme === "dark" ? "dark" : "dream";
      document.documentElement.dataset.theme = next;
      document.documentElement.style.colorScheme = next === "dark" ? "dark" : "light";
      themeIcon.textContent = next === "dark" ? "☀" : "☾";
      const label = document.querySelector(".theme-label");
      if (label) {
        const language = languageSelect.value || "zh-Hant";
        label.textContent = (translations[language] || translations["zh-Hant"])[next === "dark" ? "themeDark" : "themeDream"];
      }
      themeToggle.setAttribute("aria-label", next === "dark" ? "Switch to dreamy theme" : "Switch to dark theme");
      themeToggle.title = next === "dark" ? "Dreamy theme" : "Dark theme";
      const themeColor = document.querySelector('meta[name="theme-color"]');
      if (themeColor) themeColor.content = next === "dark" ? "#121525" : "#eaf0ff";
      try { localStorage.setItem("nemu-theme", next); } catch (_) {}
    }
    themeToggle.addEventListener("click", () => {
      setTheme(document.documentElement.dataset.theme === "dark" ? "dream" : "dark");
    });

    function setLanguage(language) {
      const dictionary = translations[language] || translations["zh-Hant"];
      document.documentElement.lang = language;
      document.title = {
        "zh-Hant": "Nemu's Sekai · Nevaline Saelina",
        ja: "Nemu's Sekai · Nevaline Saelina",
        en: "Nemu's Sekai · Nevaline Saelina",
        fr: "Nemu's Sekai · Nevaline Saelina",
        de: "Nemu's Sekai · Nevaline Saelina"
      }[language];

      document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
          // A small number of hero descriptions intentionally include a bold phrase.
          if (key === "heroCopy") element.innerHTML = dictionary[key];
          else element.textContent = dictionary[key];
        }
      });
      languageSelect.value = language;
      try { localStorage.setItem("nemu-language", language); } catch (_) {}
      const themeLabel = document.querySelector(".theme-label");
      if (themeLabel) themeLabel.textContent = dictionary[document.documentElement.dataset.theme === "dark" ? "themeDark" : "themeDream"];
      document.querySelectorAll("[data-i18n]").forEach((element) => {
        if (element.tagName === "A" && element.closest(".nav")) {
          element.setAttribute("aria-label", element.textContent.trim());
        }
      });
    }

    languageSelect.addEventListener("change", (event) => setLanguage(event.target.value));

    menuToggle.addEventListener("click", () => {
      const isOpen = nav.classList.toggle("is-open");
      menuToggle.setAttribute("aria-expanded", String(isOpen));
    });

    nav.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => {
        nav.classList.remove("is-open");
        menuToggle.setAttribute("aria-expanded", "false");
      });
    });

